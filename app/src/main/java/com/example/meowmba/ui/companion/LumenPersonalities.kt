    private val byId = scenes.associateBy { it.performance.id }
    fun find(id: String?) = byId[id]
    private fun beat(at: Int, tilt: Float = 0f, eye: Float = 1f, gaze: Float = 0f,
        bounce: Float = 0f, wag: Float = 0f, happy: Boolean = false) = AnimFrame(at,
        eyeOpen = eye, pupilSize = .28f, pupilGazeUp = gaze, headTiltDeg = tilt,
        earPerk = 1f + bounce, earDroopDeg = 0f, happyEyes = happy,
        whiskerFlutter = false, mouth = if (happy) MouthMode.HAPPY else MouthMode.IDLE,
        tongueOut = 0f, bodyBounce = bounce, tailWag = wag, sparkle = 0f)
    private fun scene(id: String, title: String, animal: AvatarAnimal, prop: SignatureProp,
        action: String, duration: Int, beats: List<AnimFrame>) = SignatureScene(animal, prop, action,
        AvatarPerformance("signature_$id", title, "Scenes", action, PerformanceAccent.SIGNATURE,
            CustomAnimationSpec(title, listOf(beat(0)) + beats.take(3) + beats[2].copy(atMs = 2750) + beats.drop(3) + beat(duration)),
            setOf("play $title"), ambient = false))
